-- Applied on every start; everything is idempotent.

CREATE TABLE IF NOT EXISTS users (
    username   text PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_login timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS drink_types (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL UNIQUE,
    volume_ml       integer NOT NULL,
    alcohol_percent real NOT NULL,
    unit_name       text NOT NULL
);

CREATE TABLE IF NOT EXISTS parties (
    code          text PRIMARY KEY,
    status        text NOT NULL DEFAULT 'NOMINATION' CHECK (status IN ('NOMINATION', 'VOTING', 'RESULTS')),
    current_round integer NOT NULL DEFAULT 1,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS attendees (
    party_code text NOT NULL REFERENCES parties ON DELETE CASCADE,
    username   text NOT NULL REFERENCES users,
    joined_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (party_code, username)
);

CREATE TABLE IF NOT EXISTS options (
    party_code text NOT NULL REFERENCES parties ON DELETE CASCADE,
    name       text NOT NULL,
    app_id     integer,
    image_url  text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (party_code, name)
);
CREATE UNIQUE INDEX IF NOT EXISTS options_party_lower_name ON options (party_code, lower(name));

-- One ballot per attendee and round; choices is {"option name": -1|0|1}.
CREATE TABLE IF NOT EXISTS ballots (
    party_code text NOT NULL REFERENCES parties ON DELETE CASCADE,
    round      integer NOT NULL,
    username   text NOT NULL,
    choices    jsonb NOT NULL,
    PRIMARY KEY (party_code, round, username)
);

CREATE TABLE IF NOT EXISTS beers (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    party_code      text NOT NULL,
    attendee        text NOT NULL,
    drink_name      text NOT NULL DEFAULT 'Beer',
    beer_equivalent real NOT NULL DEFAULT 1.0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (party_code, attendee) REFERENCES attendees ON DELETE CASCADE
);
ALTER TABLE beers ADD COLUMN IF NOT EXISTS drink_name text NOT NULL DEFAULT 'Beer';
ALTER TABLE beers ADD COLUMN IF NOT EXISTS beer_equivalent real NOT NULL DEFAULT 1.0;
CREATE INDEX IF NOT EXISTS beers_party ON beers (party_code);

-- Default presets, merged on every start so changes here reach existing databases.
-- Presets are matched by their fixed id, so they can be renamed here. Never reuse or
-- renumber an id; edits made to presets at runtime are overwritten.
MERGE INTO drink_types AS t
USING (VALUES
    ( 1, 'Beer',                  500,   5.0, 'Half liter'),
    ( 2, 'Vodka',                  20,  40.0, 'Shot'),
    ( 3, 'Wine',                  125,  12.0, 'Glass'),
    ( 4, 'Spritzer',              250,   6.0, 'Glass'),
    ( 5, 'Jägermeister',           20,  35.0, 'Shot'),
    ( 6, 'Berliner Luft',          20,  18.0, 'Shot'),
    ( 7, 'Klopfer',                20,  16.0, 'Shot'),
    ( 8, 'Gin',                    20,  40.0, 'Shot'),
    ( 9, 'Nut Schnapps',           20,  30.0, 'Shot'),
    (10, 'Jägermeister Orange',    20,  35.0, 'Shot'),
    (11, 'Tatra Tea Black',        20,  52.0, 'Shot'),
    (12, 'White Rum',              20,  37.5, 'Shot'),
    (13, 'Xuxu',                   20,  15.0, 'Shot'),
    (14, 'Jägermeister Winter',    20,  35.0, 'Shot')
) AS v (id, name, volume_ml, alcohol_percent, unit_name)
ON t.id = v.id
WHEN MATCHED AND (t.name, t.volume_ml, t.alcohol_percent, t.unit_name)
              IS DISTINCT FROM (v.name, v.volume_ml, v.alcohol_percent::real, v.unit_name) THEN
    UPDATE SET name = v.name, volume_ml = v.volume_ml, alcohol_percent = v.alcohol_percent, unit_name = v.unit_name
WHEN NOT MATCHED THEN
    INSERT (id, name, volume_ml, alcohol_percent, unit_name)
    VALUES (v.id, v.name, v.volume_ml, v.alcohol_percent, v.unit_name);

-- Explicit ids don't advance the identity sequence; without this, the next custom
-- drink would try to take id 1 and fail.
SELECT setval(pg_get_serial_sequence('drink_types', 'id'), (SELECT max(id) FROM drink_types));
